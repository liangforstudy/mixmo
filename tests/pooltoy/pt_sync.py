#!/usr/bin/env python3
"""pt_sync.py - copies the pooltoy block from the Pooltoy Water Lab into Mixmo.html.

  python3 pt_sync.py pooltoy-water-lab.html Mixmo.html          write the pooltoy's parts into Mixmo.html
  python3 pt_sync.py pooltoy-water-lab.html Mixmo.html --check  only check that Mixmo.html has the lab's current block

The block is edited only in the lab. In Mixmo it is a generated copy, in three marked places:
  - CSS (end of the first <style>): the rules between "POOLTOY CSS begin / end" in the lab, scoped to .ptroot,
    with the pooltoy's element ids prefixed pt_;
  - markup (a <template id="pt_tpl"> before the first <script>): the lab's "POOLTOY VIEW" and "POOLTOY PANEL" parts,
    ids prefixed pt_; Mixmo clones it when the pooltoy is first shown;
  - script (after the last </script>): function PT_make(HOST){...}, the lab's block without its "LAB ONLY" parts.
Each generated part carries a fingerprint of its own text. If a part in Mixmo no longer matches its fingerprint, it
was edited by hand: the script stops and changes nothing (--force overwrites anyway).
"""
import sys, re, hashlib
args = sys.argv[1:]
check = "--check" in args; force = "--force" in args
args = [a for a in args if not a.startswith("--")]
LAB, MIX = args[:2]
lab = open(LAB, encoding="utf-8").read(); mix = open(MIX, encoding="utf-8").read()
fp = lambda t: hashlib.sha1(t.encode()).hexdigest()[:12]

def between(s, a, b):
    i = s.index(a); j = s.index(b, i)
    return s[i + len(a):j]
def drop_lab_only(js):
    out, skip = [], False
    for ln in js.split("\n"):
        if ln.lstrip().startswith("// LAB ONLY begin"): skip = True; continue
        if ln.lstrip().startswith("// LAB ONLY end"): skip = False; continue
        if not skip: out.append(ln)
    if skip: sys.exit("a LAB ONLY part has no end")
    return "\n".join(out)

css = between(lab, "/* POOLTOY CSS begin", "/* POOLTOY CSS end */")
css = css[css.index("*/") + 2:].strip("\n")
view = between(lab, "<!-- POOLTOY VIEW begin -->", "<!-- POOLTOY VIEW end -->")
panel = between(lab, "<!-- POOLTOY PANEL begin -->", "<!-- POOLTOY PANEL end -->").strip("\n")
blk = between(lab, "// POOLTOY BLOCK begin", "// POOLTOY BLOCK end")
blk = blk[blk.index("\n") + 1:]          # the rest of the "begin" line is its own comment
blk = drop_lab_only(blk).rstrip("\n")

ids = set(re.findall(r'\bid="([^"]+)"', view + panel))
def pre_markup(h):
    h = re.sub(r'\b(id|for)="([^"]+)"', lambda m: '%s="pt_%s"' % (m.group(1), m.group(2)) if m.group(2) in ids else m.group(0), h)
    return h
def pre_css(c):
    out = []
    for ln in c.split("\n"):
        m = re.match(r"^([^{]+)\{(.*)$", ln)
        if not m: out.append(ln); continue
        sels = [s.strip() for s in m.group(1).split(",")]
        sels = [".ptroot " + re.sub(r"#([\w-]+)", lambda k: "#pt_" + k.group(1) if k.group(1) in ids else k.group(0), s) for s in sels]
        out.append(",".join(sels) + "{" + m.group(2))
    return "\n".join(out)

src = fp(blk + css + view + panel)
def part(kind, body, open_, close):
    return "%s POOLTOY %s begin: generated by pt_sync.py from the lab (block %s, text %s); edit it in the lab, not here %s\n%s\n%s POOLTOY %s end %s" % (
        open_, kind, src, fp(body), close, body, open_, kind, close)
GEN = {
    "CSS": part("CSS", pre_css(css), "/*", "*/"),
    "MARKUP": part("MARKUP", '<template id="pt_tpl"><div class="pt-view">%s</div><div class="pt-panel">\n%s\n</div></template>' % (pre_markup(view), pre_markup(panel)), "<!--", "-->"),
    "SCRIPT": "<script>\n" + part("SCRIPT", 'function PT_make(HOST){"use strict";\n' + blk + "\n}", "//", "") + "\n</script>",
}
PAT = {"CSS": r"/\* POOLTOY CSS begin.*?/\* POOLTOY CSS end \*/",
       "MARKUP": r"<!-- POOLTOY MARKUP begin.*?<!-- POOLTOY MARKUP end -->",
       "SCRIPT": r"<script>\n// POOLTOY SCRIPT begin.*?// POOLTOY SCRIPT end \n</script>"}

found = {k: re.search(p, mix, re.S) for k, p in PAT.items()}
if check:
    bad = [k for k in GEN if not found[k] or found[k].group(0) != GEN[k]]
    print("in step with the lab" if not bad else "NOT in step with the lab: " + ", ".join(bad) + " (run pt_sync.py without --check)")
    sys.exit(1 if bad else 0)
for k, m in found.items():          # hand edits?
    if not m: continue
    t = m.group(0); hdr = re.search(r"text (\w+)\)", t).group(1)
    body = t.split("\n", 1)[1].rsplit("\n", 1)[0] if k != "SCRIPT" else t.split("\n", 2)[2].rsplit("\n", 2)[0]
    if fp(body) != hdr and not force:
        sys.exit("STOP: Mixmo's pooltoy %s was edited by hand (its text no longer matches its fingerprint). Move the edit into the lab, or run with --force to overwrite it." % k)
out = mix
for k in GEN:
    if found[k]: out = out.replace(found[k].group(0), GEN[k])
    elif k == "CSS": i = out.index("</style>"); out = out[:i] + GEN[k] + "\n" + out[i:]
    elif k == "MARKUP": i = out.index("<script>"); out = out[:i] + GEN[k] + "\n" + out[i:]
    else: i = out.rindex("</script>") + len("</script>"); out = out[:i] + "\n" + GEN[k] + out[i:]
if out == mix: print("already in step with the lab (block %s)" % src)
else: open(MIX, "w", encoding="utf-8").write(out); print("wrote the pooltoy block %s into %s" % (src, MIX))
